def validate_parentheses_minimal():
    """Проверяет баланс и минимальность скобок: отсутствие вложенностей и отсутствие скобок в категориях/тегах."""
    errors = []
    for idx, item in enumerate(FAQ_ITEMS, 1):
        for field in ("question", "category", "body"):
            text = item[field]
            if text.count("(") != text.count(")"):
                errors.append(f"Элемент #{idx} поле '{field}': несовпадение скобок ({text.count('(')} != {text.count(')')})")
            if "((" in text or "))" in text:
                errors.append(f"Элемент #{idx} поле '{field}': обнаружены вложенные скобки")
        if "(" in item["category"] or ")" in item["category"]:
            errors.append(f"Элемент #{idx} категория содержит скобки: {item['category']}")
        for tag in item.get("tags", []):
            if "(" in tag or ")" in tag:
                errors.append(f"Элемент #{idx} тег '{tag}' содержит скобки")

    if errors:
        print("ОШИБКА валидации скобок в FAQ!", file=sys.stderr)
        for err in errors:
            print(" -", err, file=sys.stderr)
        sys.exit(1)
    print("Проверка пройдена: скобки сбалансированы, вложенности нет, количество минимально и по существу.")

