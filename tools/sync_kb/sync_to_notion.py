def check_no_parentheses():
    """Проверяет отсутствие круглых скобок в вопросах, категориях, тегах и ответах."""
    errors = []
    for idx, item in enumerate(FAQ_ITEMS, 1):
        for field in ("question", "category", "body"):
            text = item[field]
            if "(" in text or ")" in text:
                errors.append(f"Элемент #{idx} поле '{field}' содержит скобки: {text[:60]}...")
        for tag in item.get("tags", []):
            if "(" in tag or ")" in tag:
                errors.append(f"Элемент #{idx} тег '{tag}' содержит скобки")
    if errors:
        print("ОШИБКА: найдены скобки в FAQ!", file=sys.stderr)
        for err in errors:
            print(" -", err, file=sys.stderr)
        sys.exit(1)
    print("Проверка пройдена: в вопросах, категориях, тегах и текстах ответов круглых скобок НЕТ.")

