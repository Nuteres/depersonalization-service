def api_request(endpoint, data=None, method="GET", timeout=45, max_retries=5):
    url = f"https://api.notion.com/v1/{endpoint}"
    payload = json.dumps(data).encode("utf-8") if data is not None else None

    for attempt in range(1, max_retries + 1):
        req = urllib.request.Request(url, data=payload, headers=HEADERS, method=method)
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            err = e.read().decode("utf-8")
            if e.code in (429, 500, 502, 503, 504) and attempt < max_retries:
                wait_time = attempt * 2
                print(f"HTTP {e.code} on {method} {url}, повтор через {wait_time}с (попытка {attempt}/{max_retries})...")
                time.sleep(wait_time)
                continue
            print(f"HTTP Error {e.code} on {method} {url}: {err}", file=sys.stderr)
            raise
        except (urllib.error.URLError, ConnectionResetError, TimeoutError, Exception) as e:
            if attempt < max_retries:
                wait_time = attempt * 2
                print(f"Сетевой сбой ({e}) на {method} {url}, повтор через {wait_time}с (попытка {attempt}/{max_retries})...")
                time.sleep(wait_time)
                continue
            raise

